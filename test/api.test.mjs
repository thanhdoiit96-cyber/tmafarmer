import assert from 'node:assert/strict';
import test from 'node:test';
import {readFileSync} from 'node:fs';
import {DatabaseSync} from 'node:sqlite';
import worker from '../server/worker.mjs';
import {homeBed} from '../public/home-rules.mjs';
import {orderList,unixNow} from '../public/game.mjs';

test('two guest sessions share durable D1-style state with atomic sales, presence and area chat',async()=>{
  const db=new DatabaseSync(':memory:');
  for(const migration of ['0000_rooms','0001_scene_social'])db.exec(readFileSync(new URL('../drizzle/'+migration+'.sql',import.meta.url),'utf8'));
  const DB={prepare(sql){
    const query=db.prepare(sql);
    return {bind(...params){return {first:async()=>query.get(...params),all:async()=>({results:query.all(...params)}),run:async()=>({meta:query.run(...params)})};}};
  }};
  const api=async(path,data,session)=>{
    const headers=session?{authorization:'Bearer '+session.token,'x-room-code':session.code}:{};
    const response=await worker.fetch(new Request('https://farm.example/api/'+path,{
      method:data?'POST':'GET',headers,body:data?JSON.stringify(data):undefined,
    }),{DB});
    return {status:response.status,...await response.json()};
  };
  const a=await api('join',{name:'Vườn Sen'});
  const b=await api('join',{name:'Vườn Bắp',code:a.code});
  const c=await api('join',{name:'Vườn Lúa',code:a.code});
  assert.equal(a.status,201);
  assert.equal(b.status,201);
  assert.equal((await api('state',null,a)).state.neighbors.length,2);
  assert.equal((await api('state',null,{...a,token:'0'.repeat(64)})).status,401);
  const requestId=crypto.randomUUID();
  const sow={requestId,action:'plant',item:'wheat',index:0};
  const requests=await Promise.all([api('action',sow,a),api('action',sow,a)]);
  assert.ok(requests.every(r=>r.status===200&&r.state.me.inventory.wheatSeed===4));
  const row=db.prepare('SELECT state FROM farm_rooms WHERE code=?').get(a.code);
  const state=JSON.parse(row.state);
  state.farms[a.state.me.id].plots[0].at=unixNow()-600;
  state.farms[a.state.me.id].plots[0].wetUntil=unixNow()+60;
  state.created-=600;
  state.farms[a.state.me.id].inventory.carrot=4;
  db.prepare('UPDATE farm_rooms SET state=? WHERE code=?').run(JSON.stringify(state),a.code);
  const send=(player,action,payload={})=>api('action',{requestId:crypto.randomUUID(),action,...payload},player);
  const stole=await send(b,'steal',{target:a.state.me.id,source:'barn',item:'carrot'});
  assert.equal(stole.state.me.inventory.carrot,1);
  assert.match((await api('state',null,a)).state.me.log[0].message,/Vườn Bắp/);
  assert.equal((await send(b,'steal',{target:a.state.me.id,source:'garden',index:0})).status,400);
  assert.equal((await send(a,'harvest',{index:0})).state.me.inventory.wheat,3);
  const listed=await send(a,'list',{item:'wheat',qty:3,price:7});
  assert.equal(listed.state.listings.length,1);
  const transactions=await Promise.all([send(b,'deal',{index:1}),send(c,'deal',{index:1})]);
  assert.deepEqual(transactions.map(x=>x.status).sort(),[200,400]);
  assert.equal((await api('state',null,a)).state.me.coins,121);
  assert.equal((await api('state',null,a)).state.listings.length,0);
  assert.equal((await send(a,'aquaStock',{index:0,item:'tilapia',qty:1})).status,200);
  const mixed=await send(a,'aquaStock',{index:0,item:'prawn',qty:1});
  assert.deepEqual(mixed.state.me.pondBatches[0].map(batch=>batch.kind),['tilapia','prawn']);
  const pose={x:140,y:180,facing:'right',walking:true};
  const enter=(p,area,host)=>api('scene',{area,host,pose},p);
  assert.equal((await enter(a,'lake')).players.length,0);
  assert.equal((await api('scene',{area:'lake',pose:{...pose,x:900}},a)).status,400);
  const onLake=await enter(b,'lake');
  assert.deepEqual(onLake.players.map(p=>p.name),['Vườn Sen']);
  assert.equal(onLake.players[0].walking,1);
  assert.equal((await enter(c,'market')).players.length,0);
  assert.equal((await api('chat',{area:'lake',text:'Chào hồ',nonce:crypto.randomUUID()},c)).status,409);
  const message={area:'lake',text:'  Chào  hồ làng! ',nonce:crypto.randomUUID()};
  const greetings=await Promise.all([api('chat',message,b),api('chat',message,b)]);
  assert.ok(greetings.every(r=>r.status===200));
  const lakeChat=await enter(a,'lake');
  assert.deepEqual(lakeChat.messages.map(m=>m.text),['Chào hồ làng!']);
  assert.equal((await enter(c,'market')).messages.length,0);
  assert.equal((await enter(a,'field')).players.length,0);
  const guest=await enter(c,'visit',a.state.me.id);
  assert.equal(guest.players[0].name,'Vườn Sen');
  assert.equal(guest.messages.length,0);
  assert.equal((await enter(a,'field')).players[0].name,'Vườn Lúa');
  assert.equal((await enter(a,'visit',a.state.me.id)).status,400);
  db.prepare('UPDATE farm_presence SET seen=? WHERE player=?').run(unixNow()-10,c.state.me.id);
  assert.equal((await enter(a,'field')).players.length,0);
  assert.equal((await enter(b,'field')).players.length,0);
  assert.equal((await send(a,'rest')).status,400);
  assert.equal((await enter(a,'home')).status,200);
  assert.equal((await send(a,'rest')).status,400);
  assert.equal((await api('scene',{area:'home',pose:{...pose,...homeBed}},a)).status,200);
  assert.equal((await enter(c,'home',a.state.me.id)).players.length,0);
  const rest={action:'rest',requestId:crypto.randomUUID()};
  const resting=await api('action',rest,a);
  assert.equal(resting.status,200);
  assert.ok(resting.state.me.wellness.restUntil>resting.state.now);
  const retry=await api('action',rest,a);
  assert.equal(retry.state.me.wellness.restUntil,resting.state.me.wellness.restUntil);
  assert.equal((await send(a,'plant',{item:'wheat',index:0})).status,400);
  const current=(await api('state',null,a)).state;
  const order=orderList(current.day)[0];
  const {item,qty}=order.items[0];
  const stockpile=JSON.parse(db.prepare('SELECT state FROM farm_rooms WHERE code=?').get(a.code).state);
  for(const player of [a,b])stockpile.farms[player.state.me.id].inventory[item]=qty;
  db.prepare('UPDATE farm_rooms SET state=? WHERE code=?').run(JSON.stringify(stockpile),a.code);
  const finishes=await Promise.all([send(a,'order',{index:order.id}),send(b,'order',{index:order.id})]);
  assert.deepEqual(finishes.map(entry=>entry.status).sort(),[200,400]);
  const [afterA,afterB]=await Promise.all([api('state',null,a),api('state',null,b)]);
  assert.ok([afterA,afterB].every(entry=>entry.state.village.orders===1&&entry.state.orders.every(open=>open.id!==order.id)));
  assert.equal((afterA.state.me.inventory[item]??0)+(afterB.state.me.inventory[item]??0),qty);
  const funding=JSON.parse(db.prepare('SELECT state FROM farm_rooms WHERE code=?').get(a.code).state);
  funding.village.fund=180;
  db.prepare('UPDATE farm_rooms SET state=? WHERE code=?').run(JSON.stringify(funding),a.code);
  const donations=await Promise.all([send(a,'villageFund',{item:'notice',amount:70}),send(b,'villageFund',{item:'notice',amount:70})]);
  assert.deepEqual(donations.map(entry=>entry.status).sort(),[200,400]);
  assert.equal((await api('state',null,c)).state.village.fund,250);
  const onSale=JSON.parse(db.prepare('SELECT state FROM farm_rooms WHERE code=?').get(a.code).state);
  onSale.farms[a.state.me.id].inventory.wheat=27;
  db.prepare('UPDATE farm_rooms SET state=? WHERE code=?').run(JSON.stringify(onSale),a.code);
  const sale={action:'sell',source:'all',item:'wheat',requestId:crypto.randomUUID()};
  const receipts=await Promise.all([api('action',sale,a),api('action',sale,a)]);
  assert.ok(receipts.every(r=>r.status===200&&r.state.me.inventory.wheat===0));
  assert.equal(receipts[0].state.village.income,onSale.village.income+162);
  assert.equal(receipts[0].state.me.coins,receipts[1].state.me.coins);
  const bulk=JSON.parse(db.prepare('SELECT state FROM farm_rooms WHERE code=?').get(a.code).state);
  Object.assign(bulk.farms[a.state.me.id],{coins:1000});
  bulk.farms[a.state.me.id].inventory.aquaFeed=68;
  db.prepare('UPDATE farm_rooms SET state=? WHERE code=?').run(JSON.stringify(bulk),a.code);
  const purchase={action:'buy',item:'aquaFeed',qty:30,requestId:crypto.randomUUID()};
  const buys=await Promise.all([api('action',purchase,a),api('action',purchase,a)]);
  assert.ok(buys.every(r=>r.status===200&&r.state.me.inventory.aquaFeed===98&&r.state.me.coins===850));
  const over=await send(a,'buy',{item:'aquaFeed',qty:3});
  assert.equal(over.status,400);
  assert.match(over.error,/100 món/);
  const tooExpensive=await send(a,'buy',{item:'carpSeed',qty:40});
  assert.equal(tooExpensive.status,400);
  assert.match(tooExpensive.error,/đủ xu/);
  assert.equal((await api('state',null,a)).state.me.coins,850);
  db.close();
});

test('registered account can attach to a room and persist its session', async()=>{
  const db=new DatabaseSync(':memory:');
  for(const migration of ['0000_rooms','0001_scene_social'])db.exec(readFileSync(new URL('../drizzle/'+migration+'.sql',import.meta.url),'utf8'));
  const DB={prepare(sql){
    const query=db.prepare(sql);
    return {bind(...params){return {first:async()=>query.get(...params),all:async()=>({results:query.all(...params)}),run:async()=>({meta:query.run(...params)})};}};
  }};
  const api=async(path,data,session)=>{
    const headers={};
    if(session?.token) headers.authorization='Bearer '+session.token;
    if(session?.code) headers['x-room-code']=session.code;
    const response=await worker.fetch(new Request('https://farm.example/api/'+path,{method:data?'POST':'GET',headers,body:data?JSON.stringify(data):undefined}),{DB});
    return {status:response.status,...await response.json()};
  };
  const guest=await api('join',{name:'Tài khoản test'});
  assert.equal(guest.status,201);
  const registered=await api('account/register',{username:'demo-user',password:'secret123',roomCode:guest.code,farmId:guest.state.me.id});
  assert.equal(registered.status,200);
  assert.equal(registered.account.username,'demo-user');
  const login=await api('account/login',{username:'demo-user',password:'secret123'});
  assert.equal(login.status,200);
  const me=await api('account/me',null,{token:login.token});
  assert.equal(me.status,200);
  assert.ok(me.rooms.some(room=>room.roomCode===guest.code));
  db.close();
});
