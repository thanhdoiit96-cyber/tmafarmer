import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {DatabaseSync} from 'node:sqlite';
import worker from '../server/worker.mjs';
import {plotPosition} from '../public/world-layout.mjs';

test('server rechecks exact host and opt in; concurrent releases and exchanges are atomic',async()=>{
  const db=new DatabaseSync(':memory:');
  for(const name of ['0000_rooms','0001_scene_social','0002_accounts'])db.exec(readFileSync(new URL('../drizzle/'+name+'.sql',import.meta.url),'utf8'));
  const DB={prepare(sql){const q=db.prepare(sql);return {bind(...args){return {first:async()=>q.get(...args),all:async()=>({results:q.all(...args)}),run:async()=>({meta:q.run(...args)})};}};}};
  const api=async(path,payload,session)=>{
    const response=await worker.fetch(new Request('https://farm.test/api/'+path,{method:'POST',headers:session?{authorization:'Bearer '+session.token,'x-room-code':session.code}:{},body:JSON.stringify(payload)}),{DB});
    return {status:response.status,...await response.json()};
  };
  const a=await api('join',{name:'Vườn A'}),b=await api('join',{name:'Vườn B',code:a.code}),c=await api('join',{name:'Vườn C',code:a.code});
  const aid=a.state.me.id,bid=b.state.me.id;
  const read=()=>JSON.parse(db.prepare('SELECT state FROM farm_rooms WHERE code=?').get(a.code).state);
  const update=fn=>{const room=read();fn(room);db.prepare('UPDATE farm_rooms SET state=? WHERE code=?').run(JSON.stringify(room),a.code);};
  update(room=>{for(const farm of Object.values(room.farms))Object.assign(farm,{xp:70,prankJars:2,prankEnabled:true,lakeMarks:6});room.farms[bid].plots[0]={kind:'wheat',goal:10000,progress:3000,at:Math.floor(Date.now()/1000),pests:0,protectedUntil:1e12};});
  const send=(who,action,props={},requestId=crypto.randomUUID())=>api('action',{action,...props,requestId},who);
  const enter=(who,host)=>api('scene',{area:'visit',host,pose:{...plotPosition(0),facing:'up',walking:false}},who);
  const input={target:bid,index:0};
  assert.equal((await send(a,'releasePrank',input)).status,400);
  await enter(a,c.state.me.id);assert.equal((await send(a,'releasePrank',input)).status,400);
  await enter(a,bid);await enter(c,bid);
  await send(b,'prankPreference',{item:'off'});
  assert.equal((await send(a,'releasePrank',input)).status,400);
  assert.equal(read().farms[aid].prankJars,2);
  await send(b,'prankPreference',{item:'on'});
  const idA=crypto.randomUUID(),idC=crypto.randomUUID();
  const attempts=await Promise.all([send(a,'releasePrank',input,idA),send(c,'releasePrank',input,idC)]);
  assert.deepEqual(attempts.map(r=>r.status).sort(),[200,400]);
  const winner=attempts[0].status===200?a:c,requestId=winner===a?idA:idC;
  assert.equal((await send(winner,'releasePrank',input,requestId)).status,200);
  const state=read();assert.equal(state.farms[bid].prankDaily.received,1);
  assert.equal(state.farms[winner.state.me.id].prankJars,1);
  assert.equal(state.farms[aid].daily.taken,0);
  assert.equal(state.farms[bid].plots[0].pests,0);
  assert.equal((await send(b,'catchPrank',{index:0})).status,400);
  await api('scene',{area:'field',pose:{...plotPosition(0),facing:'up',walking:false}},b);
  const caught=await send(b,'catchPrank',{index:0});assert.equal(caught.status,200);
  assert.equal(caught.state.me.inventory.spray,1);
  await send(b,'prankPreference',{item:'off'});await send(b,'prankPreference',{item:'on'});
  assert.equal(read().farms[bid].prankImmuneUntil,state.farms[bid].prankImmuneUntil);
  update(room=>{room.farms[aid].prankJars=0;});
  await api('scene',{area:'lake',pose:{x:326,y:350,facing:'up',walking:false}},a);
  const exchanges=await Promise.all([send(a,'lakeExchange',{item:'prankJar'}),send(a,'lakeExchange',{item:'aquaFeed'})]);
  assert.deepEqual(exchanges.map(r=>r.status).sort(),[200,400]);
  assert.equal(read().farms[aid].lakeMarks,4);
  db.close();
});
