import assert from 'node:assert/strict';
import test from 'node:test';
import {apply,cropHazard,cropRequirement,crops,cropYield,goods,newRoom,newFarm,projectPlot,snapshot,slotLength,weedWeatherRate} from '../public/game.mjs';
import {farmTasks} from '../public/tasks.mjs';
import {playerLocationBlock} from '../public/world-layout.mjs';
const start=10000;
function setup(){const room=newRoom(start),farm=room.farms.a=newFarm('a','A',start);return {room,farm};}
const plot=(extra={})=>({kind:'corn',goal:1500,at:start,progress:0,pests:0,weeds:0,hazard:'weeds',wetUntil:start+10000,protectedUntil:0,fertilized:false,picked:0,...extra});
test('weeds respect weather, protection boundaries and projection chunking; old crops remain pest-only',()=>{
  const {room}=setup();
  assert.ok(weedWeatherRate.rain>weedWeatherRate.sun&&weedWeatherRate.fog>weedWeatherRate.heat);
  const original=plot({weedProtectedUntil:start+120});
  const first=projectPlot(room,original,start+100);
  assert.equal(first.weeds,0);assert.equal(first.pests,0);
  const all=projectPlot(room,original,start+500);
  const split=projectPlot(room,projectPlot(room,original,start+200),start+500);
  assert.ok(all.weeds>0);assert.equal(all.pests,0);
  assert.ok(Math.abs(all.progress-split.progress)<1e-7);
  assert.ok(Math.abs(all.weeds-split.weeds)<1e-7);
  const legacy=projectPlot(room,{...plot(),hazard:undefined,weeds:undefined},start+500);
  assert.equal(cropHazard(legacy),'pests');assert.equal(legacy.weeds,0);assert.ok(legacy.pests>0);
  const rainy=projectPlot(room,plot({at:start+slotLength}),start+slotLength+100);
  const sunny=projectPlot(room,plot(),start+100);
  assert.ok(rainy.weeds>sunny.weeds);
  const crossing=plot({weeds:38,weedProtectedUntil:start+120});
  const entire=projectPlot(room,crossing,start+500);
  const pieces=projectPlot(room,projectPlot(room,crossing,start+300),start+500);
  assert.ok(entire.weeds>=40);
  assert.ok(Math.abs(entire.progress-pieces.progress)<1e-7);
  assert.ok(Math.abs(entire.weeds-pieces.weeds)<1e-7);
});
test('unchecked weeds slow growth and lower yield, and weeding uses no consumables or repeated rewards',()=>{
  const {room,farm}=setup();
  farm.wellness={water:100,food:100,stamina:100,at:start,until:{},restUntil:0};
  farm.plots[0]=plot({goal:7200,weeds:45,weedPeak:45});
  const clean=projectPlot(room,plot({weedProtectedUntil:start+9999}),start+200);
  const infested=projectPlot(room,farm.plots[0],start+200);
  assert.ok(infested.progress<clean.progress);
  assert.ok(cropYield(infested)<cropYield(clean));
  const spray=farm.inventory.spray;
  assert.throws(()=>apply(room,'a',{action:'spray',index:0},start),/nhổ cỏ/);
  assert.equal(farm.inventory.spray,spray);
  const before={...farm.inventory},stamina=farm.wellness.stamina;
  apply(room,'a',{action:'weed',index:0},start);
  assert.equal(farm.plots[0].weeds,0);assert.equal(farm.plots[0].weedProtectedUntil,start+1200);
  assert.deepEqual(farm.inventory,before);assert.equal(farm.wellness.stamina,stamina-5);
  assert.equal(farm.plots[0].weedPeak,45);
  assert.throws(()=>apply(room,'a',{action:'weed',index:0},start),/không có cỏ/);
  assert.equal(farm.wellness.stamina,stamina-5);
  assert.match(playerLocationBlock({action:'weed',index:0},'field',{x:0,y:0}),/gần ô đất/);
  assert.equal(projectPlot(room,farm.plots[0],start+1199).weeds,0);
  assert.ok(projectPlot(room,farm.plots[0],start+1250).weeds>0);
});
test('new planting assigns one hazard; weed tasks and visitor snapshots agree on index zero',()=>{
  const {room,farm}=setup();farm.plots[0]=plot({weeds:25});
  const state=snapshot(room,farm,start);
  assert.ok(farmTasks(state).some(task=>task.index===0&&task.title==='Nhổ cỏ'));
  room.farms.b=newFarm('b','B',start);
  assert.equal(snapshot(room,room.farms.b,start).neighbors[0].plots[0].weeds,25);
  farm.plots[0]=null;apply(room,'a',{action:'plant',item:'wheat',index:0},start);
  assert.ok(['pests','weeds'].includes(farm.plots[0].hazard));
  assert.equal(farm.plots[0].pests,0);assert.equal(farm.plots[0].weeds,0);
});
test('truffle sits below later crops economically and keeps the documented XP gate',()=>{
  assert.equal(crops.truffle.xp,2200);
  assert.ok(goods.truffleSeed.buy<goods.coffeeSeed.buy&&goods.coffeeSeed.buy<goods.lotusSeed.buy);
  assert.ok(goods.truffle.sell<goods.coffee.sell&&goods.coffee.sell<goods.lotus.sell);
  const hourly=kind=>(goods[kind].sell*crops[kind].yield-goods[crops[kind].seed].buy)*3600/crops[kind].time;
  assert.ok(hourly('truffle')<hourly('coffee')&&hourly('truffle')<hourly('lotus'));
  assert.match(cropRequirement({workshop:3,xp:2199},'truffle'),/2200 XP/);
  assert.equal(cropRequirement({workshop:3,xp:2200},'truffle'),'');
});
