import test from 'node:test';
import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {readFileSync} from 'node:fs';
import worker from '../server/worker.mjs';
import {plotPosition} from '../public/world-layout.mjs';
test('social actions validate target presence and CAS replays cannot duplicate gifts or exchanges',async()=>{
  const db=new DatabaseSync(':memory:');
  for(const migration of ['0000_rooms','0001_scene_social','0002_accounts'])db.exec(readFileSync(new URL('../drizzle/'+migration+'.sql',import.meta.url),'utf8'));
  const DB={prepare(sql){const q=db.prepare(sql);return {bind(...args){return {first:async()=>q.get(...args),all:async()=>({results:q.all(...args)}),run:async()=>({meta:q.run(...args)})};}};}};
  const api=async(path,data,session)=>{
    const r=await worker.fetch(new Request('https://farm.example/api/'+path,{method:'POST',headers:session?{authorization:'Bearer '+session.token,'x-room-code':session.code}:{},body:JSON.stringify(data)}),{DB});
    return {status:r.status,...await r.json()};
  };
  const a=await api('join',{name:'Vườn A'}),b=await api('join',{name:'Vườn B',code:a.code}),c=await api('join',{name:'Vườn C',code:a.code});
  const read=()=>JSON.parse(db.prepare('SELECT state FROM farm_rooms WHERE code=?').get(a.code).state);
  const change=fn=>{const state=read();fn(state);db.prepare('UPDATE farm_rooms SET state=? WHERE code=?').run(JSON.stringify(state),a.code);};
  change(state=>{
    const at=Math.floor(Date.now()/1000);
    state.farms[b.state.me.id].plots[0]={kind:'wheat',progress:0,at,wetUntil:0};
    Object.assign(state.farms[a.state.me.id],{xp:25,lakeMarks:4,fishBook:{minnow:{count:1,firstAt:at},tilapia:{count:1,firstAt:at},goldenCarp:{count:1,firstAt:at}}});
  });
  const enter=(area,host,pose)=>api('scene',{area,host,pose:{...pose,facing:'up',walking:false}},a);
  const help={requestId:crypto.randomUUID(),action:'helpWater',target:b.state.me.id,index:0};
  assert.equal((await api('action',help,a)).status,400);
  const p=plotPosition(0);
  await enter('visit',c.state.me.id,p);
  assert.equal((await api('action',help,a)).status,400);
  await enter('visit',b.state.me.id,p);
  const helped=await Promise.all([api('action',help,a),api('action',help,a)]);
  assert.ok(helped.every(r=>r.status===200));
  assert.equal(read().farms[a.state.me.id].neighborHelp.given,1);
  assert.equal(read().farms[a.state.me.id].daily.taken,0);
  const start={requestId:crypto.randomUUID(),action:'shoreStart'};
  assert.equal((await api('action',start,a)).status,400);
  await enter('lake',undefined,{x:326,y:350});
  assert.equal((await api('action',start,a)).status,200);
  assert.equal((await api('action',{requestId:crypto.randomUUID(),action:'shoreTick'},a)).state.me.lakeMarks,4);
  await enter('lake',undefined,{x:50,y:350});
  assert.equal((await api('action',{requestId:crypto.randomUUID(),action:'shoreTick'},a)).status,400);
  const exchange={requestId:crypto.randomUUID(),action:'lakeExchange'};
  const result=await Promise.all([api('action',exchange,a),api('action',exchange,a)]);
  assert.ok(result.every(r=>r.status===200));
  assert.equal(read().farms[a.state.me.id].lakeMarks,2);
  const claim={requestId:crypto.randomUUID(),action:'claimFishBook'};
  assert.ok((await Promise.all([api('action',claim,a),api('action',claim,a)])).every(r=>r.status===200));
  assert.equal(read().farms[a.state.me.id].decorVouchers,1);
  assert.equal((await api('action',{...claim,requestId:crypto.randomUUID()},a)).status,400);
  db.close();
});
