"""Export transparent pig and duck sprites in the approved sheep art style."""
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
INPUT = ROOT / "docs/assets/livestock-additions-v1-source-generated.png"
SOURCE_OUT = ROOT / "docs/assets/additional-livestock-v1-source.png"
ATLAS_OUT = ROOT / "public/pixel/additional-livestock-v1.png"
PREVIEW_OUT = ROOT / "docs/assets/additional-livestock-v1-preview.png"
FRAMES_OUT = ROOT / "public/pixel/additional-livestock-frames-v1.mjs"
KINDS = ("pig", "duck")
LABELS = ("PIG", "DUCK")
POSES = ("idle", "walkA", "walkB", "feed")
CELL_W, CELL_H, SCALE = 56, 48, 4


def clean_background(frame):
    pixels = frame.load()
    for y in range(frame.height):
        for x in range(frame.width):
            r, g, b, a = pixels[x, y]
            # The generator used a checkerboard preview instead of alpha.
            # Its near-neutral whites/grays are cleanly separated from the
            # warm cream and pink animal palette.
            if min(r, g, b) >= 230 and max(r, g, b) - min(r, g, b) <= 22:
                pixels[x, y] = (r, g, b, 0)
    return frame


def frame_at(sheet, row, col):
    left = round(col * sheet.width / 2)
    right = round((col + 1) * sheet.width / 2)
    top = round(row * sheet.height / 4)
    bottom = round((row + 1) * sheet.height / 4)
    frame = clean_background(sheet.crop((left, top, right, bottom)).convert("RGBA"))
    bounds = frame.getchannel("A").getbbox()
    if not bounds:
        raise ValueError(f"Empty livestock frame {row=}, {col=}")
    return frame.crop(bounds)


def export():
    sheet = clean_background(Image.open(INPUT).convert("RGBA"))
    sheet.save(INPUT, optimize=True)
    bounds = {kind: [frame_at(sheet, row, col).size for row in range(4)]
              for col, kind in enumerate(KINDS)}
    scales = {}
    for kind in KINDS:
        max_w = max(size[0] for size in bounds[kind])
        max_h = max(size[1] for size in bounds[kind])
        scales[kind] = min((CELL_W - 4) / max_w, (CELL_H - 4) / max_h)

    atlas = Image.new("RGBA", (CELL_W * 2, CELL_H * 4), (0, 0, 0, 0))
    source = Image.new("RGBA", (CELL_W * SCALE * 2, CELL_H * SCALE * 4), (0, 0, 0, 0))
    metadata = {}
    for col, kind in enumerate(KINDS):
        scale = scales[kind]
        for row in range(4):
            frame = frame_at(sheet, row, col)
            size = (max(1, round(frame.width * scale * SCALE)),
                    max(1, round(frame.height * scale * SCALE)))
            frame = frame.resize(size, Image.Resampling.NEAREST)
            high = Image.new("RGBA", (CELL_W * SCALE, CELL_H * SCALE), (0, 0, 0, 0))
            high.alpha_composite(frame, ((high.width - size[0]) // 2, high.height - size[1] - SCALE))
            # Retain crisp silhouette edges in both master and runtime export.
            alpha = high.getchannel("A").point(lambda value: 255 if value >= 128 else 0)
            high.putalpha(alpha)
            source.alpha_composite(high, (col * CELL_W * SCALE, row * CELL_H * SCALE))
            cell = high.resize((CELL_W, CELL_H), Image.Resampling.NEAREST)
            remove_tiny_components(cell, 4)
            atlas.alpha_composite(cell, (col * CELL_W, row * CELL_H))
            metadata.setdefault(kind, {})[POSES[row]] = [col * CELL_W, row * CELL_H, CELL_W, CELL_H]

    source.save(SOURCE_OUT, optimize=True)
    atlas.save(ATLAS_OUT, optimize=True)
    lines = [f"  {kind}:{{" + ", ".join(f"{pose}:{frame}" for pose, frame in values.items()) + "},"
             for kind, values in metadata.items()]
    FRAMES_OUT.write_text("// Generated by scripts/normalize-additional-livestock-v1.py.\nexport default {\n" +
                          "\n".join(lines) + "\n};\n", encoding="utf-8")
    make_preview(atlas)
    print("Wrote the 112x192 RGBA pig/duck atlas, transparent 4x source, metadata and preview.")


def remove_tiny_components(image, threshold):
    alpha = image.getchannel("A")
    pixels = alpha.load()
    seen = set()
    for y in range(image.height):
        for x in range(image.width):
            if not pixels[x, y] or (x, y) in seen:
                continue
            stack = [(x, y)]
            component = []
            seen.add((x, y))
            while stack:
                px, py = stack.pop()
                component.append((px, py))
                for ny in range(max(0, py - 1), min(image.height, py + 2)):
                    for nx in range(max(0, px - 1), min(image.width, px + 2)):
                        if pixels[nx, ny] and (nx, ny) not in seen:
                            seen.add((nx, ny))
                            stack.append((nx, ny))
            if len(component) <= threshold:
                for px, py in component:
                    image.putpixel((px, py), (0, 0, 0, 0))


def make_preview(atlas):
    margin, label_w, cell, gap, head_h = 20, 120, 192, 12, 30
    width = margin * 2 + label_w + 5 * (cell + gap)
    height = margin * 2 + 28 + 2 * (head_h + cell + gap)
    board = Image.new("RGBA", (width, height), "#18231f")
    draw = ImageDraw.Draw(board)
    font = ImageFont.load_default()
    draw.text((margin, margin), "PIG + DUCK  |  SHEEP STYLE / RUNTIME @ 4x", font=font, fill="#f4e4c2")
    sheep = Image.open(ROOT / "public/pixel/livestock-v2.png").convert("RGBA").crop((56, 0, 112, 48))
    for species, label in enumerate(LABELS):
        y = margin + 28 + species * (head_h + cell + gap)
        draw.text((margin, y + 8), label, font=font, fill="#e0bd83")
        board.alpha_composite(sheep.resize((cell, cell), Image.Resampling.NEAREST), (margin + label_w, y + head_h))
        draw.text((margin + label_w + 3, y + 3), "STYLE REF: SHEEP", font=font, fill="#cbd4c1")
        for pose in range(4):
            x = margin + label_w + (pose + 1) * (cell + gap)
            sprite = atlas.crop((species * CELL_W, pose * CELL_H,
                                 (species + 1) * CELL_W, (pose + 1) * CELL_H))
            board.alpha_composite(sprite.resize((cell, cell), Image.Resampling.NEAREST), (x, y + head_h))
            draw.text((x + 3, y + 3), f"{POSES[pose].upper()} 56x48 @ 4x", font=font, fill="#cbd4c1")
    board.save(PREVIEW_OUT, optimize=True)


if __name__ == "__main__":
    export()
