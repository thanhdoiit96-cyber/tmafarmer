"""Export the six new crop rows and their trimmed sprite bounds."""

import json
from pathlib import Path
from PIL import Image


ROOT = Path(__file__).resolve().parents[1]
CELL, BASELINE = 48, 42
X_EDGES = (0, 365, 710, 1052, 1448)
SHEETS = [
    ("crop-stages-orchard-source.png", (0, 330, 712, 1086), ("tomato", "sunflower", "strawberry")),
    ("crop-stages-special-source.png", (0, 365, 712, 1086), ("grape", "tea", "truffle")),
]


def extract(frame):
    alpha = frame.getchannel("A").point(lambda value: 255 if value >= 245 else 0)
    bounds = alpha.getbbox()
    if not bounds:
        raise ValueError("Empty crop frame")
    frame.putalpha(alpha)
    return frame.crop(bounds)


def export():
    atlas = Image.new("RGBA", (4 * CELL, 6 * CELL))
    meta = {}
    for sheet, (filename, rows, crops) in enumerate(SHEETS):
        image = Image.open(ROOT / "docs/assets" / filename).convert("RGBA")
        if image.size != (X_EDGES[-1], rows[-1]):
            raise ValueError(f"Unexpected image size: {image.size}")
        for row, (kind, top, bottom) in enumerate(zip(crops, rows, rows[1:])):
            frames = [extract(image.crop((left, top, right, bottom))) for left, right in zip(X_EDGES, X_EDGES[1:])]
            ratio = min(43 / max(frame.width for frame in frames), 40 / max(frame.height for frame in frames))
            cells = []
            atlas_y = (sheet * 3 + row) * CELL
            for stage, frame in enumerate(frames):
                width, height = [round(length * ratio) for length in frame.size]
                reduced = frame.resize((width, height), Image.Resampling.LANCZOS)
                alpha = reduced.getchannel("A").point(lambda value: 255 if value >= 145 else 0)
                cell = Image.new("RGBA", (CELL, CELL))
                cell.paste(reduced.convert("RGB"), ((CELL - width) // 2, BASELINE - height), alpha)
                atlas.paste(cell, (stage * CELL, atlas_y))
                cells.append(cell.getchannel("A").getbbox())
            meta[kind] = {"y": atlas_y, "bounds": cells}
    path = ROOT / "public/pixel"
    atlas.save(path / "crop-stages.png", optimize=True)
    lines = [f"  {key}:{json.dumps(value, separators=(',', ':'))}," for key, value in meta.items()]
    (path / "crop-stages-frames.mjs").write_text(
        "// Generated by scripts/normalize-crop-stages.py.\nexport default {\n" + "\n".join(lines) + "\n};\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    export()
