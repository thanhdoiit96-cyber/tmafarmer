"""Export four sheep-style livestock sprites and their action poses."""
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
INPUT = ROOT / "docs/assets/livestock-v3-source-generated.png"
SOURCE_OUT = ROOT / "docs/assets/progression-livestock-v2-source.png"
ATLAS_OUT = ROOT / "public/pixel/progression-livestock-v2.png"
PREVIEW_OUT = ROOT / "docs/assets/progression-livestock-v2-preview.png"
FRAMES_OUT = ROOT / "public/pixel/progression-livestock-frames-v2.mjs"

KINDS = ("chicken", "cow", "quail", "buffalo")
LABELS = ("CHICKEN", "DAIRY COW", "QUAIL", "WATER BUFFALO")
CELL_W, CELL_H = 56, 48
SCALE = 4


def frame_at(sheet, row, col):
    box = (round(col*sheet.width/4), round(row*sheet.height/4),
           round((col+1)*sheet.width/4), round((row+1)*sheet.height/4))
    frame = sheet.crop(box).convert("RGBA")
    alpha = frame.getchannel("A").point(lambda value: 255 if value >= 128 else 0)
    if row == 3 and col == 2:
        # The generated quail-feeding cell contains a stray edge fragment;
        # its body stays inside the same horizontal envelope as its walk poses.
        alpha.paste(0, (310, 0, frame.width, frame.height))
    frame.putalpha(alpha)
    bounds = alpha.getbbox()
    if not bounds:
        raise ValueError(f"Empty livestock frame {row=}, {col=}")
    return frame.crop(bounds)


def remove_specks(image, threshold=3):
    alpha = image.getchannel("A")
    pixels = alpha.load()
    w, h = image.size
    seen = set()
    for y in range(h):
        for x in range(w):
            if not pixels[x,y] or (x,y) in seen:
                continue
            stack=[(x,y)]; component=[]; seen.add((x,y))
            while stack:
                px,py=stack.pop(); component.append((px,py))
                for ny in range(max(0,py-1),min(h,py+2)):
                    for nx in range(max(0,px-1),min(w,px+2)):
                        if pixels[nx,ny] and (nx,ny) not in seen:
                            seen.add((nx,ny)); stack.append((nx,ny))
            if len(component)<=threshold:
                for px,py in component:
                    image.putpixel((px,py),(0,0,0,0))


def export():
    sheet=Image.open(INPUT).convert("RGBA")
    # One scale per species keeps its idle, walking and feeding silhouettes
    # registered to the same size and ground baseline.
    bounds={}
    for col,kind in enumerate(KINDS):
        bounds[kind]=[frame_at(sheet,row,col).size for row in range(4)]
    scales={}
    for kind in KINDS:
        max_w=max(size[0] for size in bounds[kind]); max_h=max(size[1] for size in bounds[kind])
        scales[kind]=min((CELL_W-2)/max_w,(CELL_H-3)/max_h)

    atlas=Image.new("RGBA",(CELL_W*4,CELL_H*4),(0,0,0,0))
    source=Image.new("RGBA",(CELL_W*4*SCALE,CELL_H*4*SCALE),(0,0,0,0))
    metadata={}
    for col,kind in enumerate(KINDS):
        scale=scales[kind]
        for row in range(4):
            frame=frame_at(sheet,row,col)
            size=(max(1,round(frame.width*scale*SCALE)),max(1,round(frame.height*scale*SCALE)))
            frame=frame.resize(size,Image.Resampling.NEAREST)
            high=Image.new("RGBA",(CELL_W*SCALE,CELL_H*SCALE),(0,0,0,0))
            high.alpha_composite(frame,((CELL_W*SCALE-size[0])//2,CELL_H*SCALE-size[1]-SCALE))
            remove_specks(high,threshold=12*SCALE*SCALE)
            source.alpha_composite(high,(col*CELL_W*SCALE,row*CELL_H*SCALE))
            cell=high.resize((CELL_W,CELL_H),Image.Resampling.NEAREST)
            remove_specks(cell,threshold=12)
            atlas.alpha_composite(cell,(col*CELL_W,row*CELL_H))
            metadata.setdefault(kind,{"x":col*CELL_W,"frames":[]})["frames"].append([col*CELL_W,row*CELL_H,CELL_W,CELL_H])

    atlas.save(ATLAS_OUT,optimize=True)
    source.save(SOURCE_OUT,optimize=True)
    lines=[]
    pose_names=("idle","walkA","walkB","feed")
    for kind,entry in metadata.items():
        poses=", ".join(f"{name}:{frame}" for name,frame in zip(pose_names,entry["frames"]))
        lines.append(f"  {kind}:{{{poses}}},")
    FRAMES_OUT.write_text(
        "// Generated by scripts/normalize-progression-livestock-v2.py.\nexport default {\n"+"\n".join(lines)+"\n};\n",
        encoding="utf-8")
    make_preview(atlas)
    print("Wrote the 224x192 RGBA livestock action atlas, 4x master, metadata and comparison preview.")


def make_preview(atlas):
    margin,label_w,cell,gap,head_h=20,120,192,12,30
    width=margin*2+label_w+5*(cell+gap)
    height=margin*2+4*(head_h+cell+gap)
    board=Image.new("RGBA",(width,height),"#18231f")
    d=ImageDraw.Draw(board); font=ImageFont.load_default()
    d.text((margin,margin),"LIVESTOCK V2  |  SHEEP STYLE / RUNTIME @ 4x",font=font,fill="#f4e4c2")
    sheep=Image.open(ROOT/"public/pixel/livestock-v2.png").convert("RGBA").crop((56,0,112,48))
    for species,label in enumerate(LABELS):
        y=margin+28+species*(head_h+cell+gap)
        d.text((margin,y+8),label,font=font,fill="#e0bd83")
        board.alpha_composite(sheep.resize((cell,cell),Image.Resampling.NEAREST),(margin+label_w,y+head_h))
        d.text((margin+label_w+3,y+3),"STYLE REF: SHEEP",font=font,fill="#cbd4c1")
        for pose in range(4):
            x=margin+label_w+(pose+1)*(cell+gap)
            sprite=atlas.crop((species*CELL_W,pose*CELL_H,(species+1)*CELL_W,(pose+1)*CELL_H))
            board.alpha_composite(sprite.resize((cell,cell),Image.Resampling.NEAREST),(x,y+head_h))
            name=("IDLE","WALK A","WALK B","FEED")[pose]
            d.text((x+3,y+3),f"{name} 56x48 @ 4x",font=font,fill="#cbd4c1")
    board.save(PREVIEW_OUT,optimize=True)


if __name__=="__main__":
    export()
