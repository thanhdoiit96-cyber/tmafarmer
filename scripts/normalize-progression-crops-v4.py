"""Normalize the approved late-game crop concept to the 48px game grid."""
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
INPUT = ROOT / "docs/assets/progression-crops-v4-source-generated.png"
SOURCE_OUT = ROOT / "docs/assets/progression-crops-v4-source.png"
ATLAS_OUT = ROOT / "public/pixel/progression-crops-v4.png"
PREVIEW_OUT = ROOT / "docs/assets/progression-crops-v4-preview.png"
FRAMES_OUT = ROOT / "public/pixel/progression-crop-frames-v4.mjs"

KINDS = ("coffee", "lotus", "dragonfruit", "blackRice")
LABELS = ("COFFEE", "LOTUS", "DRAGON FRUIT", "BLACK RICE")
CELL = 48
SOURCE_SCALE = 4


def clean_frame(frame):
    """Discard low-alpha fringe and remove chroma-green generation halos."""
    rgba = frame.convert("RGBA")
    pix = rgba.load()
    w, h = rgba.size
    for y in range(h):
        for x in range(w):
            r, g, b, a = pix[x, y]
            # Keep the art's saturated leaf highlights, but remove the pure
            # green spill the generator placed just outside some silhouettes.
            if a < 190 or (g > 175 and r < 85 and b < 90 and g - r > 100):
                pix[x, y] = (0, 0, 0, 0)
            else:
                pix[x, y] = (r, g, b, 255)
    bbox = rgba.getchannel("A").getbbox()
    if not bbox:
        raise ValueError("Crop cell has no opaque pixels")
    return rgba.crop(bbox)


def fit_frame(frame, row):
    # Keep a consistent ground baseline and leave room for the silhouette.
    max_w = 44 if row == 2 else 42
    max_h = 41
    ratio = min(max_w / frame.width, max_h / frame.height)
    size = (max(1, round(frame.width * ratio)), max(1, round(frame.height * ratio)))
    # The source is an illustration; nearest sampling converts its edges into
    # deliberate hard clusters on the game's native 48px grid.
    sprite = frame.resize(size, Image.Resampling.NEAREST)
    cell = Image.new("RGBA", (CELL, CELL), (0, 0, 0, 0))
    cell.alpha_composite(sprite, ((CELL-size[0])//2, 42-size[1]))
    remove_specks(cell)
    return cell


def remove_specks(cell):
    """Remove disconnected one-off pixels left where generated cells touch."""
    alpha = cell.getchannel("A")
    pixels = alpha.load()
    seen = set()
    w, h = cell.size
    for y in range(h):
        for x in range(w):
            if pixels[x, y] == 0 or (x, y) in seen:
                continue
            stack = [(x, y)]
            component = []
            seen.add((x, y))
            while stack:
                px, py = stack.pop()
                component.append((px, py))
                for ny in range(max(0, py-1), min(h, py+2)):
                    for nx in range(max(0, px-1), min(w, px+2)):
                        if pixels[nx, ny] and (nx, ny) not in seen:
                            seen.add((nx, ny))
                            stack.append((nx, ny))
            if len(component) <= 20:
                for px, py in component:
                    cell.putpixel((px, py), (0, 0, 0, 0))


def export():
    sheet = Image.open(INPUT).convert("RGBA")
    src_w, src_h = sheet.size
    frames = []
    for row in range(4):
        for col in range(4):
            box = (round(col*src_w/4), round(row*src_h/4),
                   round((col+1)*src_w/4), round((row+1)*src_h/4))
            frames.append(fit_frame(clean_frame(sheet.crop(box)), row))

    atlas = Image.new("RGBA", (CELL*4, CELL*4), (0, 0, 0, 0))
    metadata = {}
    for index, frame in enumerate(frames):
        col, row = index % 4, index // 4
        atlas.alpha_composite(frame, (col*CELL, row*CELL))
        alpha = frame.getchannel("A")
        bounds = alpha.getbbox()
        metadata.setdefault(KINDS[row], {"row": row, "bounds": []})["bounds"].append(list(bounds))
    atlas.save(ATLAS_OUT, optimize=True)
    lines = [f"  {kind}:{{row:{meta['row']},bounds:{meta['bounds']}}}," for kind, meta in metadata.items()]
    FRAMES_OUT.write_text("// Generated by scripts/normalize-progression-crops-v4.py.\nexport default {\n" + "\n".join(lines) + "\n};\n", encoding="utf-8")

    source = atlas.resize((CELL*4*SOURCE_SCALE, CELL*4*SOURCE_SCALE), Image.Resampling.NEAREST)
    source.save(SOURCE_OUT, optimize=True)
    make_preview(atlas)
    print(f"Wrote {ATLAS_OUT.name} (192x192 RGBA), {SOURCE_OUT.name} (768x768), and comparison preview.")


def make_preview(atlas):
    # Show existing pixel-art quality reference beside every 1x and 4x stage.
    margin, label_w, cell, gap, head_h = 20, 120, 192, 10, 32
    board = Image.new("RGBA", (margin*2 + label_w + 8*(cell+gap), margin*2 + 4*(head_h+cell+gap)), "#18231f")
    from PIL import ImageDraw, ImageFont
    d = ImageDraw.Draw(board)
    font = ImageFont.load_default()
    d.text((margin, margin), "LATE-GAME CROPS V4  |  REFERENCE / RUNTIME @ 4x", font=font, fill="#f4e4c2")
    old = Image.open(ROOT / "public/pixel/progression-crops-v2.png").convert("RGBA")
    refs = (old.crop((144,0,192,48)), old.crop((144,48,192,96)), old.crop((144,144,192,192)), old.crop((336,96,384,144)))
    for row, label in enumerate(LABELS):
        y = margin + 28 + row*(head_h+cell+gap)
        d.text((margin, y+8), label, font=font, fill="#e0bd83")
        ref = refs[row].resize((cell, cell), Image.Resampling.NEAREST)
        board.alpha_composite(ref, (margin+label_w, y+head_h))
        d.text((margin+label_w+4,y+4), "STYLE REFERENCE", font=font, fill="#cbd4c1")
        for stage in range(4):
            x = margin+label_w+(1+stage*2)*(cell+gap)
            frame = atlas.crop((stage*CELL,row*CELL,(stage+1)*CELL,(row+1)*CELL))
            board.alpha_composite(frame.resize((cell,cell),Image.Resampling.NEAREST),(x,y+head_h))
            d.text((x+4,y+4),f"STAGE {stage+1}  48px @ 4x",font=font,fill="#cbd4c1")
    board.save(PREVIEW_OUT,optimize=True)


if __name__ == "__main__":
    export()
